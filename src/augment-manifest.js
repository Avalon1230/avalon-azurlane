export const AUGMENT_RECORDS=Object.keys(AUGMENTS).length;
export function augmentRecord(sourceId){
  const id=String(sourceId??'').replace(/^aug-/,'');
  if(!/^\d{4,8}$/.test(id)||!Object.hasOwn(AUGMENTS,id))return null;
  const [name,type,group,rarity,obtainable,craftable,serverEN,stats]=AUGMENTS[id];
  return {
    id:'aug-'+id,sourceId:id,kind:'augment',source:'source-augment',
    name,typeCode:type,limitGroup:group,rarityCode:rarity,
    rarity:({3:'Rare',4:'Elite',5:'Super Rare'})[rarity]||'Unverified',
    obtainable:!!obtainable,craftable:!!craftable,serverEN:!!serverEN,
    stats:stats.map(([key,max,random])=>({key,max,random})),
    category:'Augment',sourceUrl:AUGMENT_SOURCE
  };
}
export function candidateAugmentsForShip({shipId=null,hullId=null}={}){
  if(!Number.isSafeInteger(hullId))return [];
  const candidates=[];
  for(const id of Object.keys(AUGMENTS)){
    const [name,type,group,rarity,obtainable,craftable,serverEN]=AUGMENTS[id];
    if(!obtainable||!serverEN)continue;
    if(group>0){if(shipId===null||group!==shipId)continue;}
    else if(!AUGMENT_HULLS[type]?.includes(hullId))continue;
    const item=augmentRecord(id);
    item.matchLevel=group>0?'ship-specific':'class';
    candidates.push(item);
  }
  return candidates.sort((a,b)=>
    (b.matchLevel==='ship-specific')-(a.matchLevel==='ship-specific')||
    b.rarityCode-a.rarityCode||a.name.localeCompare(b.name)||Number(a.sourceId)-Number(b.sourceId)
  );
}
export function augmentHullIds(typeCode){
  return AUGMENT_HULLS[typeCode]?.slice()||[];
}
