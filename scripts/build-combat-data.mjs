import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const bytes=readFileSync(new URL('../data/combat-source.json',import.meta.url));
const raw=JSON.parse(bytes);
const hash=createHash('sha256').update(bytes).digest('hex');
const code='// Generated by scripts/build-combat-data.mjs; see docs/COMBAT_MECHANICS.md and THIRD_PARTY_NOTICES.md.\n'+
  'export const COMBAT_SOURCE_SHA256 = '+JSON.stringify(hash)+';\n'+
  'export const COMBAT_DATA = '+JSON.stringify(raw)+';\n';
const target=new URL('../src/combat-data.js',import.meta.url);
if(process.argv.includes('--check')){
  if(readFileSync(target,'utf8')!==code)throw new Error('Combat manifest differs from audited source fixture');
}else writeFileSync(target,code);
