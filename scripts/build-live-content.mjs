// Generate the buildless browser module from AVALON's reviewed factual records.
import {readFile,writeFile} from 'node:fs/promises';
const input=new URL('../data/live-content/november-2026.json',import.meta.url);
const output=new URL('../src/live-content-data.js',import.meta.url);
const data=JSON.parse(await readFile(input,'utf8'));
const generated='// Generated by scripts/build-live-content.mjs. Edit data/live-content/november-2026.json.\n// Wiki-derived content: CC BY-NC-SA 4.0; original game assets remain their owners’ property.\nexport const LIVE_CONTENT = '+JSON.stringify(data)+';\n';
if(process.argv.includes('--check')){
  if(await readFile(output,'utf8')!==generated)throw Error('Live-content module is out of date');
}else await writeFile(output,generated);
