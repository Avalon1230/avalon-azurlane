/** Deterministic build identity for the existing static site; no bundler or cache layer. */
import {readFile,readdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('..',import.meta.url));
const hash=b=>createHash('sha256').update(b).digest('hex');
async function walk(dir){const out=[];for(const d of await readdir(resolve(root,dir),{withFileTypes:true})){const file=dir+'/'+d.name;if(d.isDirectory())out.push(...await walk(file));else if(/\.(js|css|json)$/.test(file))out.push(file);}return out;}
const metadata=JSON.parse(await readFile(resolve(root,'data/release-status.json'),'utf8'));
const paths=['index.html','CHANGELOG.md',...(await walk('src')),...(await walk('assets')),...(await walk('data'))].filter(p=>!['src/release-data.js','data/deployment.json'].includes(p)).sort();
const files={};for(const file of paths)files[file]=hash(await readFile(resolve(root,file)));
const fingerprint=hash(JSON.stringify(files));
const deployment={schemaVersion:1,version:metadata.version,status:metadata.status,fingerprint,files};
const moduleText='// Generated by scripts/build-release.mjs.\\n'.replace('\\n','\n')+'export const BUILD='+JSON.stringify({version:metadata.version,status:metadata.status,fingerprint})+';\n';
for(const [file,content] of [['data/deployment.json',JSON.stringify(deployment,null,2)+'\n'],['src/release-data.js',moduleText]]){
 if(process.argv.includes('--check'))assert.equal(await readFile(resolve(root,file),'utf8'),content,file+' is stale; run node scripts/build-release.mjs');
 else await writeFile(resolve(root,file),content);
}
console.log('PASS static build identity: '+paths.length+' files, '+metadata.version+' ('+metadata.status+')');
